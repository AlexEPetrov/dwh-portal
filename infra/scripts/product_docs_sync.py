def run_sync() -> int:
    caps_doc = load_yaml(CAPABILITIES_YAML)
    caps_root = caps_doc.get("capabilities") if isinstance(caps_doc, dict) else None
    if not isinstance(caps_root, dict):
        die("openspec/capabilities.yaml: missing top-level capabilities mapping")

    yaml_leaves = walk_capabilities(caps_root)
    yaml_by_id = {cid: desc for cid, desc in yaml_leaves}
    specs = discover_specs()

    help_doc = load_yaml(HELP_MAP) or {}
    help_by_cap: dict[str, list[str]] = {}
    for entry in help_doc.get("entries") or []:
        help_by_cap[entry["capability"]] = list(entry.get("help") or [])

    adr_doc = load_yaml(ADR_MAP) or {}
    adr_entries: list[dict[str, Any]] = list(adr_doc.get("entries") or [])
    adr_by_cap: dict[str, list[str]] = {}
    missing_adr_files: list[str] = []
    for entry in adr_entries:
        adr_rel = entry["adr"]
        adr_path = REPO_ROOT / adr_rel
        if not adr_path.is_file():
            missing_adr_files.append(adr_rel)
            continue
        title = extract_h1(adr_path.read_text(encoding="utf-8")) or Path(adr_rel).stem
        entry["_title"] = title
        entry["_path"] = adr_path
        for cap in entry.get("capabilities") or []:
            adr_by_cap.setdefault(cap, []).append(adr_rel)

    missing_in_yaml = sorted(set(specs) - set(yaml_by_id))
    missing_specs = sorted(set(yaml_by_id) - set(specs))
    missing_purpose: list[str] = []

    facts: list[CapabilityFact] = []
    # Publish intersection + warn on drift; still emit pages for yaml leaves with specs
    for cap_id in sorted(set(yaml_by_id) & set(specs)):
        spec_path = specs[cap_id]
        text = spec_path.read_text(encoding="utf-8")
        purpose = extract_purpose(text)
        if not purpose:
            missing_purpose.append(cap_id)
        title = extract_h1(text) or cap_id
        fact = CapabilityFact(
            id=cap_id,
            title=title,
            purpose=purpose,
            spec_path=spec_path.relative_to(REPO_ROOT).as_posix(),
            yaml_description=yaml_by_id.get(cap_id),
            help_topics=help_by_cap.get(cap_id, []),
            related_adrs=adr_by_cap.get(cap_id, []),
        )
        facts.append(fact)

    facts_by_id = {f.id: f for f in facts}
    audience_by_id = load_audience_map()

    clear_generated_tree()
    pages = OUT_COMPONENT / "modules" / "ROOT" / "pages"
    write_antora_yml()
    write_index()
    copy_spine_pages()
    installed_enrich = set(install_enrich_partials())

    for fact in facts:
        slug = slug_from_capability_id(fact.id)
        audience = audience_by_id.get(fact.id, "specialist")
        write_text(
            pages / "capabilities" / f"{slug}.adoc",
            render_capability_page(
                fact,
                has_enrich=slug in installed_enrich,
                audience=audience,
            ),
        )

    for entry in adr_entries:
        if "_path" not in entry:
            continue
        adr_path: Path = entry["_path"]
        slug = adr_path.stem
        write_text(
            pages / "decisions" / f"{slug}.adoc",
            render_adr_page(
                adr_path,
                entry.get("summary") or "",
                list(entry.get("capabilities") or []),
                entry.get("_title") or slug,
            ),
        )

    write_text(
        pages / "drift.adoc",
        render_drift(missing_in_yaml, missing_specs, missing_purpose, missing_adr_files),
    )
    write_text(
        OUT_COMPONENT / "modules" / "ROOT" / "nav.adoc",
        build_nav(
            caps_root,
            facts_by_id,
            [e for e in adr_entries if "_path" in e],
            audience_by_id,
        ),
    )

    facts_payload = {
        "mode": "sync",
        "enrich_capabilities": sorted(installed_enrich),
        "audiences": audience_by_id,
        "capabilities": [asdict(f) for f in facts],
        "drift": {
            "specs_missing_yaml_leaf": missing_in_yaml,
            "yaml_leaves_missing_spec": missing_specs,
            "specs_missing_purpose": missing_purpose,
            "missing_adr_files": missing_adr_files,
        },
    }
    write_text(
        OUT_FACTS / "capabilities.json",
        json.dumps(facts_payload, ensure_ascii=False, indent=2) + "\n",
    )
    write_playbook()

    # Fail closed only on orphan specs / broken Purpose / missing ADR files.
    # Yaml leaves without a spec are allowed: capabilities.yaml is a catalog of
    # directions and (future) features, not a mirror of existing specs only.
    errors: list[str] = []
    warnings: list[str] = []
    if missing_in_yaml:
        errors.append(
            f"specs without yaml leaf (every spec MUST be registered in "
            f"capabilities.yaml): {missing_in_yaml}"
        )
    if missing_specs:
        warnings.append(
            f"yaml leaves without spec (catalog placeholders): {missing_specs}"
        )
    if missing_purpose:
        errors.append(f"specs missing Purpose: {missing_purpose}")
    if missing_adr_files:
        errors.append(f"missing ADR files: {missing_adr_files}")

    print(
        f"product_docs_sync: wrote {len(facts)} capabilities, "
        f"{sum(1 for e in adr_entries if '_path' in e)} decisions, "
        f"{len(installed_enrich)} enrich → "
        f"{OUT_COMPONENT.relative_to(REPO_ROOT)}"
    )
    for warn in warnings:
        print(f"product_docs_sync: NOTE: {warn}", file=sys.stderr)
    if errors:
        for err in errors:
            print(f"product_docs_sync: DRIFT: {err}", file=sys.stderr)
        return 2
    return 0


def run_enrich() -> int:
    """Validate AI enrich layer and re-assemble the Antora component.

    This mode does not call a model API. An LLM agent must populate
    docs/generated/product-enrich/capabilities/*.adoc on explicit human
    request; then enrich re-runs sync so pages include those narratives.
    """
    enrich_caps = OUT_ENRICH / "capabilities"
    files = sorted(enrich_caps.glob("*.adoc")) if enrich_caps.is_dir() else []
    if not files:
        die(
            "mode=enrich: нет файлов в docs/generated/product-enrich/capabilities/. "
            "Сначала агент должен записать русскоязычные narrative (явный запрос человека), "
            "затем повторить --mode enrich.",
            code=3,
        )
    readme = OUT_ENRICH / "README.adoc"
    if not readme.is_file():
        write_text(
            readme,
            GENERATED_BANNER.format(mode="enrich", source="product_docs_sync")
            + """= product-enrich

Русскоязычный AI-слой продуктовой документации.

* Пишется агентом только по явному запросу человека.
* Не содержит MUST/SHALL и новых возможностей вне facts.
* Идентификаторы (`help:`, capability id, API) не переводятся.
* Подключается в компонент через `product_docs_sync.py --mode sync|enrich`.
""",
        )
    print(
        f"product_docs_sync: enrich ok — {len(files)} narratives in "
        f"{OUT_ENRICH.relative_to(REPO_ROOT)}; reassembling…"
    )
    return run_sync()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=("sync", "enrich"),
        required=True,
        help="sync = deterministic regenerate; enrich = AI layer (on request only)",
    )
    args = parser.parse_args(argv)
    if args.mode == "sync":
        return run_sync()
    return run_enrich()


if __name__ == "__main__":
    raise SystemExit(main())
