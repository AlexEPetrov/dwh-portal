#!/usr/bin/env python3
"""Deterministic product-docs sync: OpenSpec + product spine + curated ADRs → AsciiDoc.

Modes:
  sync   — rebuild docs/generated/product (no AI)
  enrich — re-assemble with AI narrative from docs/generated/product-enrich/
           (content is authored by an LLM agent on explicit human request;
           this CLI does not call a model API)

Product-facing prose is Russian-first. OpenSpec may stay English; identifiers
are not translated. Generated files are read-only by hand.
"""

